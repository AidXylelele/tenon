export const dateParsing = [
  String.raw`def strptime($format):`,
  String.raw`def unsupported: error("strptime: unsupported directive \(.)");`,
  String.raw`def directives: {`,
  String.raw`"Y": "\\d{4}", "y": "\\d\\d",`,
  String.raw`"m": "0[1-9]|1[0-2]|[1-9]", "d": "0[1-9]|[12]\\d|3[01]|[1-9]",`,
  String.raw`"j": "00[1-9]|0[1-9]\\d|[12]\\d\\d|3[0-5]\\d|36[0-6]|[1-9]\\d?",`,
  String.raw`"H": "[01]\\d|2[0-3]|\\d", "M": "[0-5]\\d|\\d", "S": "[0-5]\\d|60|\\d",`,
  String.raw`"b": "Jan(?:uary)?|Feb(?:ruary)?|Mar(?:ch)?|Apr(?:il)?|May|June?|July?|Aug(?:ust)?|Sep(?:tember)?|Oct(?:ober)?|Nov(?:ember)?|Dec(?:ember)?",`,
  String.raw`"a": "Sun(?:day)?|Mon(?:day)?|Tue(?:sday)?|Wed(?:nesday)?|Thu(?:rsday)?|Fri(?:day)?|Sat(?:urday)?",`,
  String.raw`"z": "Z|[+-]\\d\\d(?::?\\d\\d)?", "Z": "UTC|GMT|Z"`,
  String.raw`};`,
  String.raw`def expansions: {`,
  String.raw`"%T": "%H:%M:%S", "%F": "%Y-%m-%d", "%D": "%m/%d/%y",`,
  String.raw`"%e": " %d", "%B": "%b", "%A": "%a"`,
  String.raw`};`,
  String.raw`def tokens: [match("%.?|[^%]+"; "g").string];`,
  String.raw`def part:`,
  String.raw`if . == "%%" then {literal: "%"}`,
  String.raw`elif startswith("%") then .[1:] as $letter`,
  String.raw`| if directives | has($letter) then {directive: $letter} else unsupported end`,
  String.raw`else {literal: .} end;`,
  String.raw`def escaped:`,
  String.raw`explode | map([.] | implode`,
  String.raw`| if test("\\s") then "\\s*"`,
  String.raw`elif (. as $c | "\\^$.|?*+()[]{}" | contains($c)) then "\\" + .`,
  String.raw`else . end) | add;`,
  String.raw`def pattern:`,
  String.raw`if has("directive") then "(" + directives[.directive] + ")" else .literal | escaped end;`,
  String.raw`def number($letter; $absent): if has($letter) then .[$letter] | tonumber else $absent end;`,
  String.raw`def year:`,
  String.raw`if has("y") and (has("Y") | not) then number("y"; 0) | if . < 69 then . + 2000 else . + 1900 end`,
  String.raw`else number("Y"; 1970) end;`,
  String.raw`def month:`,
  String.raw`if has("j") and (has("d") | not) then 0`,
  String.raw`elif has("b") and (has("m") | not) then .b[0:3] | ascii_upcase as $name`,
  String.raw`| ["JAN", "FEB", "MAR", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC"] | index($name)`,
  String.raw`else number("m"; 1) - 1 end;`,
  String.raw`def day: if has("j") and (has("d") | not) then number("j"; 1) else number("d"; 1) end;`,
  String.raw`def offset:`,
  String.raw`if (has("z") | not) or (.z | ascii_upcase) == "Z" then 0`,
  String.raw`else .z | capture("^(?<sign>[+-])(?<hours>\\d\\d):?(?<minutes>\\d\\d)?$")`,
  String.raw`| ((.hours | tonumber) * 3600 + ((.minutes // "0") | tonumber) * 60)`,
  String.raw`* (if .sign == "-" then -1 else 1 end) end;`,
  String.raw`if type != "string" or ($format | type) != "string"`,
  String.raw`then error("strptime/1 requires string inputs and arguments")`,
  String.raw`else . as $date`,
  String.raw`| [$format | tokens[] | expansions[.] // . | tokens[] | part] as $parts`,
  String.raw`| ("^" + ($parts | map(pattern) | add // "") + "\\s*$") as $regex`,
  String.raw`| [$parts[] | .directive | values] as $letters`,
  String.raw`| (first(match($regex; "i")) // error("date \"\($date)\" does not match format \"\($format)\""))`,
  String.raw`| [range($letters | length) as $index | {key: $letters[$index], value: .captures[$index].string}]`,
  String.raw`| from_entries`,
  String.raw`| ([year, month, day, number("H"; 0), number("M"; 0), number("S"; 0)] | mktime) - offset`,
  String.raw`| gmtime end;`,
  String.raw`def fromdateiso8601: strptime("%Y-%m-%dT%H:%M:%SZ") | mktime;`,
  String.raw`def fromdate: fromdateiso8601;`,
].join(" ");
